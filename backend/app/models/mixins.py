"""模型公共 Mixin 模块。

提供全部业务表共用的列定义片段，统一对齐《02 数据库设计文档》§2.1/§2.2/§2.3：
- ``IdMixin``：主键 ``id BIGINT GENERATED BY DEFAULT AS IDENTITY``；
- ``TimestampMixin``：审计列 ``created_at`` / ``updated_at``（TIMESTAMPTZ，DB 默认 now()，
  updated_at 由 ORM onupdate 维护）；
- ``SoftDeleteMixin``：软删除列 ``deleted_at TIMESTAMPTZ NULL``（NULL 表示存活）。
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import BigInteger, DateTime, Identity, func
from sqlalchemy.orm import Mapped, mapped_column


class IdMixin:
    """主键 Mixin：所有表统一 ``id BIGINT IDENTITY`` 主键。

    Attributes:
        id: 主键，BIGINT GENERATED BY DEFAULT AS IDENTITY。
    """

    id: Mapped[int] = mapped_column(
        BigInteger,
        Identity(always=False),
        primary_key=True,
        comment="主键 ID",
    )


class TimestampMixin:
    """审计时间 Mixin：created_at / updated_at（TIMESTAMPTZ）。

    Attributes:
        created_at: 创建时间（UTC，DB 默认 now()）。
        updated_at: 末次更新时间（DB 默认 now()，ORM 更新时刷新）。
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        comment="创建时间（UTC）",
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
        comment="末次更新时间（UTC）",
    )


class SoftDeleteMixin:
    """软删除 Mixin：deleted_at 为 NULL 表示存活，非 NULL 表示已删除。

    Attributes:
        deleted_at: 软删除时间（NULL 表示未删除）。
    """

    deleted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        default=None,
        comment="软删除时间（NULL 表示存活）",
    )
